def user_case(
    case_id: str,
    category: str,
    question: str,
    **kwargs: Any,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "id": case_id,
        "category": category,
        "messages": [{"role": "user", "content": question}],
        "expect_tool": False,
        "expected_tools": [],
        "forbidden_tools": ["calculator", "current_time", "search_docs"],
        "expected_arguments": None,
        "gold_answer": None,
        "answer_contains": [],
        "success_mode": "answer_contains",
        "citations": [],
        "retrieval": None,
        "max_steps": 6,
        "min_tool_calls": 0,
        "expect_recovery": False,
        "subcategory": None,
        "notes": "",
    }
    payload.update(kwargs)
    return payload


def write_jsonl(name: str, rows: list[dict[str, Any]]) -> None:
    path = CASES / name
    path.write_text(
        "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows),
        encoding="utf-8",
    )
    print(f"{path.name}: {len(rows)}")


def retrieval_case(
    case_id: str,
    question: str,
    gold_id: str,
    answer: str,
    extra_ids: list[str],
    query: str,
) -> dict[str, Any]:
    selected = {gold_id, *extra_ids}
    corpus = [item for item in WIKI if item["id"] in selected]
    return user_case(
        case_id,
        "retrieval",
        question,
        expect_tool=True,
        expected_tools=["search_docs"],
        forbidden_tools=["calculator", "current_time"],
        gold_answer=answer,
        answer_contains=[answer],
        success_mode="cite_and_answer",
        citations=[gold_id],
        retrieval={
            "query": query,
            "k": 5,
            "gold_doc_ids": [gold_id],
            "corpus": corpus,
        },
        notes="青梧实验室虚构文档，与 SFT 课程问答独立。",
    )


